static uint8_t oled_buffer[1025] = {0x40};
static i2c_master_dev_handle_t oled_dev_handle = NULL;  // device handle

void oled_i2c_write(const uint8_t *data, size_t data_len) {
    i2c_master_transmit(oled_dev_handle, data, data_len, -1);
}

void oled_clear_screen(void) {
    memset(&oled_buffer[1], 0, 1024);
}

void oled_init(void) {
    // 1. Configure I2C Master Bus on ESP32-S3
    i2c_master_bus_config_t bus_cfg = {
        .i2c_port = I2C_NUM_0,
        .sda_io_num = I2C_SDA_GPIO,
        .scl_io_num = I2C_SCL_GPIO,
        .clk_source = I2C_CLK_SRC_DEFAULT,
        .glitch_ignore_cnt = 7,
        .flags.enable_internal_pullup = true,
    };

    i2c_master_bus_handle_t bus_handle;
    i2c_new_master_bus(&bus_cfg, &bus_handle);

    // 2. Register SSD1309 Device on I2C Bus
    i2c_device_config_t dev_cfg = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = OLED_I2C_ADDR,
        .scl_speed_hz = OLED_CLOCK_SPEED_HZ,
    };

    i2c_master_bus_add_device(bus_handle, &dev_cfg, &oled_dev_handle);

    // Allow hardware Power-On Reset (POR) circuit to settle
    vTaskDelay(pdMS_TO_TICKS(20));

    // 3. Command Array: Control Byte (0x00) + Opcode/Parameter Pairs
    static const uint8_t init_cmds[] = {
        0x00,        // Control Byte: Stream Command Mode
        0xAE,        // Display OFF (Sleep Mode)
        0xD5, 0x80,  // Set Oscillator Frequency & Clock Divide Ratio
        0xA8, 0x3F,  // Set Multiplex Ratio (1/64 duty)
        0xD3, 0x00,  // Set Display Offset to 0
        0x40,        // Set Display Start Line to 0
        0x20, 0x00,  // Set Memory Addressing Mode to Horizontal
        0xA1,        // Set Segment Re-map (Horizontal Flip)
        0xC8,        // Set COM Output Scan Direction (Vertical Flip)
        0xDA, 0x12,  // Set COM Pins Hardware Configuration
        0x81, 0x7F,  // Set Contrast Level
        0xD9, 0xF1,  // Set Pre-Charge Period
        0xDB, 0x34,  // Set VCOMH Deselect Level
        0xA4,        // Output follows GDDRAM content
        0xA6,        // Normal Display Mode (Non-inverted)
        0xAF         // Display ON
    };

    oled_i2c_write(init_cmds, sizeof(init_cmds));

    // 4. Wipe display memory noise on boot
    oled_clear_screen();
    oled_flush();
}

void oled_draw_pixel(int32_t x, int32_t y, int32_t color) {
    if (x < 0 || x >= OLED_WIDTH || y < 0 || y >= OLED_HEIGHT) {
        return;
    }

    int32_t index = 1 + x + (y / 8) * OLED_WIDTH;
    uint8_t mask  = 1 << (y % 8); 

    if (color == 1) {
        oled_buffer[index] |= mask; // Turn on
    } else {
        oled_buffer[index] &= ~mask; // Turn off
    }
}

void oled_flush(void) {
    // 1. Reset hardware window bounds
    const uint8_t set_col[]  = { 0x00, 0x21, 0x00, 0x7F };
    const uint8_t set_page[] = { 0x00, 0x22, 0x00, 0x07 };
    oled_i2c_write(set_col, sizeof(set_col));
    oled_i2c_write(set_page, sizeof(set_page));

    // 2. Transmit buffer directly
    oled_buffer[0] = 0x40;
    oled_i2c_write(oled_buffer, sizeof(oled_buffer));
}

void oled_draw_char(int32_t x, int32_t y, uint8_t c) {
    // process only vaild characters
    if (c < 32 || c > 126) {
        return;
    }

    // check if the character can be printed fully 
    if (x + 5 >= OLED_WIDTH || y + 7 >= OLED_HEIGHT) {
        return;
    }

    int32_t idx = c - 32;

    // draw character
    for (int32_t col = 0; col < 5; col++) {
        uint8_t line = ascii[idx][col];

        for (int32_t row = 0; row < 8; row++) {
            if ((line >> row) & 0x01) {
                oled_draw_pixel(x + col, y + row, 1);
            }
            else {
                oled_draw_pixel(x + col, y + row, 0);
            }
        }
    }
}

void oled_draw_string(int32_t x, int32_t y, char* str) {
    if (str == NULL || x < 0 || x > OLED_WIDTH || y < 0 || y > OLED_HEIGHT) {
        return;
    }

    for (int32_t i = 0; str[i] != '\0'; i++) {
        oled_draw_char(x + 6 * i, y, str[i]);
    }
}

void oled_print_line(int32_t line, char* str) {
    if (str == NULL || line < 0 || line > 7) {
        return;
    }

    int32_t x = 0;
    int32_t y = line * 8;            

    oled_draw_string(x, y, str);
}

void oled_highlight_line(int32_t line) {
    if (line < 0 || line > 7) return;

    // pointer to the start of the 128-byte page in memory
    uint8_t *page_start = &oled_buffer[1 + line * OLED_WIDTH];

    // flip all 8 vertical bits across all 128 columns
    for (int32_t col = 0; col < OLED_WIDTH; col++) {
        page_start[col] ^= 0xFF;
    }
}


void ui_draw_status_screen(int nozzle_temp, int bed_temp, float z_position, int progress) {
    char buffer[30];
    
    oled_clear_screen();

    spirntf(buffer, "Nozzle: %d C", nozzle_temp);
    oled_print_line(0, buffer);

    sprintf(buffer, "Bed   : %d C" ,bed_temp);
    oled_print_line(1, buffer);

    sprintf(buffer, "Z-Axis: %.2f mm" , z_position);
    oled_print_line(3, buffer);

    spirntf(buffer, "Status: %d%%", progress);
    oled_print_line(5, buffer);

    oled_print_line(7, "Read / Printing");

    oled_flush();

}

void ui_draw_main_menu(int index) {
    oled_clear_screen();
    
    oled_print_line(0, "--- MAIN MENU ---");
    oled_print_line(1, " Print File");
    oled_print_line(2, " Preheat PLA");
    oled_print_line(3, " Auto Home");
    oled_print_line(4, " Move Axis");
    oled_print_line(5, " Disable Steppers");
    oled_print_line(6, " Info");
    
    if (index >= 0 && index <= 5) {
        oled_highlight_line(index + 1);
    }
    
    oled_flush();
}